const doc = JSON.parse(await readFile(FILE, "utf8"));
doc.byConcept = doc.byConcept || {};
let added = 0;
let already = 0;
for (const [concept, words] of Object.entries(ADD)) {
  if (doc.byConcept[concept]) { already += 1; console.log(`  이미 있음 ${concept}`); continue; }
  doc.byConcept[concept] = words;
  added += 1;
  console.log(`  ${concept} ← ${words.join(" · ")}`);
}
console.log(`
더한 단원 ${added}개 · 이미 있던 것 ${already}개 · 이제 모두 ${Object.keys(doc.byConcept).length}개`);
