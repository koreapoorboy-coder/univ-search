console.log(`  수학 개념 ${mathKeys.length}개 · 새로 이은 글 ${added}편`);
for (const key of mathKeys.sort()) console.log(`    ${key.padEnd(34)} ${doc.concepts[key].length}편`);
if (missing.length) { console.log("\n  제목으로 못 찾은 것:"); missing.forEach((one) => console.log(`    ${one}`)); }

