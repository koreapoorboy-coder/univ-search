// 이미 이어져 있는 글을 모두 모아 제목으로 찾을 수 있게 한다.
const byTitle = new Map();
for (const list of Object.values(doc.concepts || {})) {
  for (const post of list) if (post?.title) byTitle.set(post.title, post);
}

let added = 0;
const missing = [];
for (const [key, titles] of Object.entries(LINK)) {
  const bag = doc.concepts[key] || [];
  const have = new Set(bag.map((one) => one.url));
  for (const part of titles) {
    const post = [...byTitle.values()].find((one) => one.title.includes(part));
    if (!post) { missing.push(`${key} ← ${part}`); continue; }
    if (have.has(post.url)) continue;
    bag.push(post);
    added += 1;
  }
  if (bag.length) doc.concepts[key] = bag;
}

const mathKeys = Object.keys(doc.concepts).filter((k) => /^(공통수학|대수|미적분|기하|확률과 통계)/.test(k));
