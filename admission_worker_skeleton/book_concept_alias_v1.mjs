const norm = (value) => String(value || '').replace(/[\s·]/g, '');
const 표 = new Map(Object.entries(BOOK_CONCEPT_ALIAS).map(([key, value]) => [norm(key), value]));

// 책에 적힌 이름 하나를 우리 단원 이름들로 펼친다. 이미 우리 이름이면 그대로 둔다.
export function aliasedConcepts(name) {
  const found = 표.get(norm(name));
  return found ? [name, ...found] : [name];
}
